"""F1 Skymark in the 3D explorer (/noida-skymark/world): the atlas engine/world.js reads.

    python noida-skymark/world/build_atlas.py ROUTES.json

ROUTES.json is what scripts/skymark/routes.py writes (the walk to Noida Sector 15 along the
OpenStreetMap streets). Writes:
  examples/skymark.bundle.json      the one option, for scripts/world/prep.py --region
                                    scripts/world/regions/noida-skymark.json
  engine/atlases/noida-skymark.js   the explorer's atlas: same sign-in as /noida-skymark/
The building's facts are the ones the /noida-skymark/ page shows (noida-skymark/data.js).
"""
import json, os, re, sys
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
routes = json.load(open(sys.argv[1]))
P = json.load(open(os.path.join(ROOT, "noida-skymark/reconstruction/facade_parameters.json")))
data = open(os.path.join(ROOT, "noida-skymark/data.js"), encoding="utf-8").read()
PR = json.loads(re.search(r"window\.SKY_PROPERTY = (\{.*?\});\n", data, re.S).group(1))
app = open(os.path.join(ROOT, "noida-skymark/app.js"), encoding="utf-8").read()
GATE = re.search(r'GATE_HASH = "([0-9a-f]{64})"', app).group(1)   # the same sign-in as the page
pin = P["map"]["pin"]
fact = lambda k: next((f["v"] for f in PR["facts"] if f["k"] == k), "")
option = {
    "id": "skymark-f1", "n": 1, "name": "F1 Skymark", "lat": pin["lat"], "lng": pin["lng"], "precision": "building",
    "micro": "sector-6", "reason": "G+4 with basements · Plot F-01, Sector 6, Noida",
    "address": "Plot No. F-01, Sector 6, Noida, Uttar Pradesh 201301", "locality": "Sector 6, Noida",
    "routes": [{**r, "src": "https://www.openstreetmap.org"} for r in routes],
    "facts": [
        {"k": "Total floors", "v": "G+4"}, {"k": "Configuration", "v": "G+4, with basements"},
        {"k": "Grade", "v": "A"}, {"k": "Building type", "v": "Commercial"},
        {"k": "Total leasable area", "v": "90,551 sq ft (developer); 45,000 sq ft (Autopilot listing)"},
        {"k": "Plot size", "v": "2,940 sq m"}, {"k": "Tenants", "v": "Care Health Insurance, Clovia, Sprint and EFC coworking, Autopilot Offices"},
        {"k": "Address", "v": "Plot No. F-01, Sector 6, Noida"},
        {"k": "Developer page", "v": "skymarkgroup.in", "src": "https://www.skymarkgroup.in/our-project-offices.html"},
    ],
}
atlas = {
    "slug": "noida-skymark", "path": "/noida-skymark/", "gate": {"hash": GATE},
    "meta": {
        "title": "F1 Skymark", "sub": "Sector 6, Noida", "city": "Noida", "center": [pin["lng"], pin["lat"]], "zoom": 16,
        "world": {"href": "/noida-skymark/world", "data": "/media/noida-skymark/world/", "sky": "sky.hdr", "poster": "hero.jpg",
                  "origin": [77.318977, 28.591317], "ky": 110950.0,
                  "brand": {"kicker": "Autopilot · F1 Skymark", "title": "Sector 6, Noida"},
                  "credit": "F1 Skymark is the Blender twin built from the client's photographs (noida-skymark/reconstruction). Around it, Overture Maps footprints with heights estimated from the Copernicus surface model. Walk to the metro: OpenStreetMap streets.",
                  "thumbs": {"skymark-f1": "r/skymark-f1-close.jpg"}, "renders": {"skymark-f1": "r/skymark-f1-street.jpg"}},
    },
    "options": [option],
    "copy": {"connect": {"note": "Walking distance from the building to Noida Sector 15 (Blue Line), along the streets in OpenStreetMap (Overture Maps 2026-10-21)."}},
}
json.dump({"options": [option]}, open(os.path.join(ROOT, "examples/skymark.bundle.json"), "w"), indent=1)
open(os.path.join(ROOT, "engine/atlases/noida-skymark.js"), "w").write(
    "/* Generated by noida-skymark/world/build_atlas.py. Do not edit: edit the script and rerun it. */\nwindow.ATLAS = " + json.dumps(atlas) + ";\n")
print("wrote examples/skymark.bundle.json and engine/atlases/noida-skymark.js:", [(r["name"], r["m"]) for r in routes])
