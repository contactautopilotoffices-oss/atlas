"""Total Environment Workcations in the 3D explorer (/te-whitefield/world), the way Noida Skymark was wired.

    python te-whitefield/world/build_atlas.py te-whitefield/world/routes.json

Writes:
  examples/te-whitefield.bundle.json   the one option, for scripts/world/prep.py --region scripts/world/regions/te-whitefield.json
  engine/atlases/te-whitefield.js      the explorer's atlas, behind the same sign-in as /whitefield/
Facts are from Autopilot's Whitefield brief (carpet area, seats, generator backup) and Total Environment (G+19).
"""
import json, os, re, sys
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
routes = [r for r in json.load(open(sys.argv[1])) if r["name"] == "Hoodi"]   # the nearer station; Sri Sathya Sai Hospital is 1.84 km
app = open(os.path.join(ROOT, "whitefield/app.js"), encoding="utf-8").read()
GATE = re.search(r'GATE_HASH = "([0-9a-f]{64})"', app).group(1)
LAT, LNG = 12.9908297, 77.7204927   # centre of the tower's footprint (Overture)
option = {
    "id": "te-workcations", "n": 1, "name": "Pursuit of a Radical Rhapsody", "lat": LAT, "lng": LNG, "precision": "building",
    "micro": "hoodi", "reason": "Workcations tower · Total Environment · ITPL Main Road, Hoodi",
    "address": "ITPL Main Road (Whitefield Road), Basavanna Nagar, Hoodi, Whitefield, Bengaluru 560048", "locality": "Hoodi, Whitefield",
    "routes": [{**r, "src": "https://www.openstreetmap.org"} for r in routes],
    "facts": [
        {"k": "Total floors", "v": "G+19"}, {"k": "Developer", "v": "Total Environment"},
        {"k": "Grade", "v": "A"}, {"k": "Building type", "v": "Commercial (managed offices by Autopilot Offices)"},
        {"k": "Carpet area", "v": "20,476 sq. ft."}, {"k": "Seats", "v": "50 to 500"},
        {"k": "Power", "v": "N+1 generator backup (building)"}, {"k": "Terrace", "v": "Double-height terrace garden"},
        {"k": "Address", "v": "ITPL Main Road, Hoodi, Whitefield"},
    ],
}
atlas = {
    "slug": "te-whitefield", "path": "/whitefield/", "gate": {"hash": GATE},
    "meta": {
        "title": "Pursuit of a Radical Rhapsody", "sub": "Hoodi, Whitefield", "city": "Bengaluru", "center": [LNG, LAT], "zoom": 16,
        "world": {"href": "/te-whitefield/world", "data": "/media/te-whitefield/world/", "sky": "sky.hdr", "poster": "hero.jpg",
                  "origin": [77.7207093, 12.9912103], "ky": 110600.0,
                  "brand": {"kicker": "Autopilot · Total Environment", "title": "Hoodi, Whitefield"},
                  "credit": "The Workcations tower is modelled in Blender from Total Environment's render, the sales model video and a street photograph. Around it, Overture Maps footprints with heights estimated from the Copernicus surface model. Walk to the metro: OpenStreetMap streets.",
                  "thumbs": {"te-workcations": "r/te-workcations-close.jpg"}, "renders": {"te-workcations": "r/te-workcations-street.jpg"}},
    },
    "options": [option],
    "copy": {"connect": {"note": "Walking distance from the site gate on ITPL Main Road to Hoodi (Purple Line), along the streets in OpenStreetMap (Overture Maps 2026-10-21)."}},
}
json.dump({"options": [option]}, open(os.path.join(ROOT, "examples/te-whitefield.bundle.json"), "w"), indent=1)
open(os.path.join(ROOT, "engine/atlases/te-whitefield.js"), "w").write(
    "/* Generated by te-whitefield/world/build_atlas.py. Do not edit: edit the script and rerun it. */\nwindow.ATLAS = " + json.dumps(atlas) + ";\n")
print("wrote examples/te-whitefield.bundle.json and engine/atlases/te-whitefield.js:", [(r["name"], r["m"]) for r in routes])
