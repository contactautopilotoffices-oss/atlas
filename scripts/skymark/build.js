#!/usr/bin/env node
/* Skymark F-1, Sector 6, Noida: writes engine/atlases/skymark-f1.js, the data
   the page at /skymark reads (engine/skymark.html, engine/skymark.js).

     node scripts/skymark/build.js

   Facts on screen come from two sources and nothing else:
     Skymark Group  "Skymark F-1": Plot No. F-01, Sector-6 Noida, G+4 with
                    basements, total leasable area 90,551 sq ft, plot
                    2,940 sq m (skymarkgroup.in, our-project-offices).
     The deck       "Design & built presentation for Volt", Autopilot,
                    21 Aug 2026: the first-floor layout, its legend and its
                    room renders (scripts/skymark/volt-floor1.json).
   The footprint is Overture Maps'; the 3D context is Google's photorealistic
   tiles where the key is set (window.GOOGLE_MAPS_KEY, from config.js), else
   our own 1 km model (scripts/skymark/context.py). */
"use strict";
const fs = require("fs"), path = require("path"), crypto = require("crypto");
const root = path.join(__dirname, "..", "..");
const ACCESS = { id: "SKYMARKDEMO", pass: "SKY1234" };
const hash = crypto.createHash("sha256").update(`${ACCESS.id}:${ACCESS.pass}`.toUpperCase().replace(/[\s-]/g, "")).digest("hex");
const volt = JSON.parse(fs.readFileSync(path.join(__dirname, "volt-floor1.json"), "utf8"));
const site = JSON.parse(fs.readFileSync(path.join(root, "media", "skymark-f1", "site.json"), "utf8"));
const data = {
  slug: "skymark", path: "/skymark", gate: { hash },
  media: "/media/skymark-f1/",
  building: {
    name: "Skymark F-1", address: "Plot No. F-01, Sector 6, Noida", lat: 28.5911248, lng: 77.319213,
    facts: [["Configuration", "G+4, with basements"], ["Total leasable area", "90,551 sq ft"], ["Plot size", "2,940 sq m"]],
    src: "https://www.skymarkgroup.in/our-project-offices.html",
    /* Storey heights are not published; these are typical for an IT block of
       this size, and only set where floors sit in the model. */
    storeys: { ground: 4.5, typical: 3.9, parapet: 1.2, count: 5 },
    floors: [
      { n: 0, label: "G", name: "Ground floor" },
      { n: 1, label: "1", name: "First floor", tenant: "Volt", deck: "Design & built presentation for Volt (Autopilot, 21 Aug 2026)" },
      { n: 2, label: "2", name: "Second floor" },
      { n: 3, label: "3", name: "Third floor" },
      { n: 4, label: "4", name: "Fourth floor" },
    ],
  },
  /* Google Street View, the panorama the client shared (in front of the
     building, looking at it). Embedded without a key. */
  streetview: { pano: "7Z1vp7p1rGI7ltpzslvdiw", lat: 28.5910204, lng: 77.3193201, heading: 336.12, pitch: -5.54 },
  site, volt,
  /* Blender Cycles renders of rooms (scripts/skymark/blender/), shown full
     screen when the room is opened. Only files that exist are listed. */
  renders: Object.fromEntries([
    ["conf18", "renders/conf18.jpg", "18 seater conference room, rendered in Blender Cycles from the plan"],
  ].filter(([, f]) => fs.existsSync(path.join(root, "media", "skymark-f1", f))).map(([id, src, caption]) => [id, { src, caption }])),
  /* films: a camera move through a room (conf18.py --film, joined with ffmpeg) */
  films: Object.fromEntries(["conf18"].filter((id) => fs.existsSync(path.join(root, "media", "skymark-f1", "films", `${id}.mp4`)))
    .map((id) => [id, { src: `films/${id}.mp4`, poster: `films/${id}-poster.jpg` }])),
  /* walk mode: 360 panoramas rendered in Cycles at the points in
     scripts/skymark/blender/walk.json; a room walks once two exist */
  walk: (() => {
    const w = JSON.parse(fs.readFileSync(path.join(__dirname, "blender", "walk.json"), "utf8")), out = {};
    for (const [room, pts] of Object.entries(w)) {
      if (!Array.isArray(pts)) continue;
      const have = pts.filter((p) => fs.existsSync(path.join(root, "media", "skymark-f1", "walk", `${room}-${p.id}.jpg`)))
        .map((p) => ({ ...p, src: `walk/${room}-${p.id}.jpg` }));
      if (have.length) out[room] = have;
    }
    return out;
  })(),
};
fs.writeFileSync(path.join(root, "engine", "atlases", "skymark-f1.js"),
  "/* Generated by scripts/skymark/build.js. Do not edit: edit the script and rerun it. */\nwindow.SKYMARK = " + JSON.stringify(data) + ";\n");
console.log("Wrote engine/atlases/skymark-f1.js", volt.rooms.length, "rooms");
