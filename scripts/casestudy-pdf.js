#!/usr/bin/env node
/* ============================================================================
   ATLAS · a case study as a PDF, from a workbook, with no CMS

     node scripts/casestudy-pdf.js examples/andheri-case.xlsx docs-out/andheri-case
       -> docs-out/andheri-case.pdf, docs-out/andheri-case.json,
          docs-out/andheri-case-p01.png ... (one PNG a page, for checking)
     node scripts/casestudy-pdf.js --demo
       -> casestudy/demo.js, the bundle /casestudy/ shows when no study is named

   The same page the CMS serves, printed by headless Chromium with the same
   print CSS, so what the team gets from "Save as PDF" is what this makes.
   ============================================================================ */
"use strict";
const fs = require("fs");
const path = require("path");
const http = require("http");
const { chromium } = require("playwright");
const { readCaseWorkbook } = require("./lib/case-workbook");
const { validate, format } = require("./lib/validate-case");

const ROOT = path.join(__dirname, "..");
const TYPES = { ".html": "text/html", ".js": "text/javascript", ".css": "text/css", ".png": "image/png", ".jpg": "image/jpeg", ".webp": "image/webp", ".svg": "image/svg+xml" };

/* A tiny static server for the page and its scripts; the bundle is injected. */
function serve() {
  return new Promise((ok) => {
    const srv = http.createServer((req, res) => {
      let p = decodeURIComponent(new URL(req.url, "http://x").pathname);
      if (p.endsWith("/")) p += "index.html";
      const file = path.join(ROOT, p);
      if (!file.startsWith(ROOT) || !fs.existsSync(file) || fs.statSync(file).isDirectory()) { res.statusCode = 404; return res.end(); }
      res.setHeader("Content-Type", TYPES[path.extname(file)] || "application/octet-stream");
      res.end(fs.readFileSync(file));
    }).listen(0, () => ok({ srv, base: `http://localhost:${srv.address().port}` }));
  });
}

async function renderPdf(bundle, outBase, { pngs = true } = {}) {
  const { srv, base } = await serve();
  const browser = await chromium.launch();
  try {
    const page = await browser.newPage({ viewport: { width: 1123, height: 794 } });
    await page.route(/fonts\.(googleapis|gstatic)\.com/, r => r.abort());
    const errors = [];
    page.on("pageerror", e => errors.push(e.message));
    await page.addInitScript((b) => { window.CASE = b; }, bundle);
    await page.goto(base + "/casestudy/", { waitUntil: "load" });
    await page.waitForSelector(".page", { timeout: 20000 });
    await page.waitForTimeout(300);
    if (errors.length) throw new Error("page errors: " + errors.join(" | "));
    const n = await page.$$eval(".page", els => els.length);
    const text = await page.$eval("#deck", e => e.textContent);
    await page.emulateMedia({ media: "print" });
    await page.pdf({ path: outBase + ".pdf", format: "A4", landscape: true, printBackground: true, margin: { top: 0, right: 0, bottom: 0, left: 0 }, preferCSSPageSize: true });
    const overflow = await page.$$eval(".page", els => els.map((el, i) => ({ page: i + 1, over: el.scrollHeight - el.clientHeight })).filter(x => x.over > 2));
    if (pngs) {
      await page.emulateMedia({ media: "screen" });
      const pages = await page.$$(".page");
      for (let i = 0; i < pages.length; i++) await pages[i].screenshot({ path: `${outBase}-p${String(i + 1).padStart(2, "0")}.png` });
    }
    return { pages: n, text, overflow };
  } finally { await browser.close(); srv.close(); }
}

async function main() {
  const args = process.argv.slice(2);
  if (args[0] === "--demo") {
    const { bundle } = await readCaseWorkbook(path.join(ROOT, "examples", "andheri-case.xlsx"));
    const out = path.join(ROOT, "casestudy", "demo.js");
    fs.writeFileSync(out, "/* The Andheri example, for /casestudy/ with no study named. Generated by scripts/casestudy-pdf.js --demo from examples/andheri-case.xlsx. */\nwindow.CASE = " + JSON.stringify(bundle) + ";\n");
    console.log(`wrote ${out}`);
    return;
  }
  const [wbPath, outBase] = args;
  if (!wbPath || !outBase) { console.error("usage: casestudy-pdf.js <workbook.xlsx> <out-base>  |  --demo"); process.exit(2); }
  const { bundle, notes } = await readCaseWorkbook(wbPath);
  const rep = validate(bundle);
  console.log(notes.filter(n => !/example row/.test(n)).join("\n"));
  console.log(format(rep));
  if (!rep.ok) process.exit(1);
  fs.mkdirSync(path.dirname(outBase), { recursive: true });
  fs.writeFileSync(outBase + ".json", JSON.stringify(bundle, null, 1));
  const r = await renderPdf(bundle, outBase);
  console.log(`${r.pages} pages -> ${outBase}.pdf${r.overflow.length ? `\n  overflowing: ${r.overflow.map(o => `p${o.page} by ${o.over}px`).join(", ")}` : ""}`);
}

if (require.main === module) main().catch(e => { console.error(e); process.exit(1); });
module.exports = { renderPdf };
